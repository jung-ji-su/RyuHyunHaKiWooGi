import { initializeTestEnvironment, assertSucceeds, assertFails } from '@firebase/rules-unit-testing';
import { readFileSync } from 'fs';
import { doc, getDoc, setDoc } from 'firebase/firestore';
const env = await initializeTestEnvironment({ projectId:'demo-rules', firestore:{ rules: readFileSync('firestore.rules','utf8') } });
const js = env.authenticatedContext('지수').firestore();
const hy = env.authenticatedContext('현하').firestore();
const other = env.authenticatedContext('stranger').firestore();
const anon = env.unauthenticatedContext().firestore();
const r=[];
const t=async(name,exp,p)=>{ try{ await (exp?assertSucceeds(p):assertFails(p)); r.push('PASS '+name);}catch(e){r.push('FAIL '+name+' -> '+String(e.message).slice(0,80));} };
await t('지수 diaries 쓰기 허용',true,setDoc(doc(js,'diaries/a'),{x:1}));
await t('현하 diaries 읽기 허용',true,getDoc(doc(hy,'diaries/a')));
await t('제3자 diaries 읽기 차단',false,getDoc(doc(other,'diaries/a')));
await t('비로그인 diaries 읽기 차단',false,getDoc(doc(anon,'diaries/a')));
await t('buckets 지수 허용',true,setDoc(doc(js,'buckets/b'),{x:1}));
await t('authAttempts 지수 쓰기 차단',false,setDoc(doc(js,'authAttempts/지수'),{count:0}));
await t('authAttempts 지수 읽기 차단',false,getDoc(doc(js,'authAttempts/지수')));
await t('authAttempts 현하 쓰기 차단',false,setDoc(doc(hy,'authAttempts/현하'),{count:0}));
console.log(r.join('\n'));
await env.cleanup();
